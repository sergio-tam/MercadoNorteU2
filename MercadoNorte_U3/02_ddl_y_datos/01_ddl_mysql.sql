/* =====================================================================
   Mercado Norte · Data Mart de Ventas · DDL para MySQL 8
   Origen: DDL_Script de la Unidad 2 (Equipo 1). Se conservan nombres de
   tablas y columnas (incluido el prefijo DMI_CLIENTE de la Unidad 2).

   AJUSTES respecto al DDL original (documentados en el reporte):
   [A1] "GENERATED ALWAYS AS IDENTITY" no es sintaxis de MySQL
        (es de PostgreSQL/Oracle/DB2) -> se usa AUTO_INCREMENT.
   [A2] Se agregan llaves únicas sobre las claves de negocio y sobre el
        grano (ORDEN_ID, LINEA_ORDEN) para impedir duplicados.
   Ningún atributo nuevo fue agregado a las tablas.
   ===================================================================== */
CREATE DATABASE IF NOT EXISTS mercado_norte
  DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE mercado_norte;

DROP TABLE IF EXISTS FACT_VENTAS_LINEA;
DROP TABLE IF EXISTS DMI_CLIENTE;
DROP TABLE IF EXISTS DIM_TIEMPO;
DROP TABLE IF EXISTS DIM_PRODUCTO;
DROP TABLE IF EXISTS DIM_SUCURSAL;
DROP TABLE IF EXISTS DIM_CANAL;
DROP TABLE IF EXISTS DIM_PROMOCION;

CREATE TABLE DMI_CLIENTE (
    CLIENTE_SK       BIGINT NOT NULL AUTO_INCREMENT,
    CLIENTE_ID       VARCHAR(50),
    NOMBRE           VARCHAR(150),
    TIPO_CLIENTE     VARCHAR(50),
    SEGMENTO         VARCHAR(50),
    CIUDAD           VARCHAR(100),
    ESTADO           VARCHAR(100),
    PAIS             VARCHAR(100),
    CONSTRAINT PK_DMI_CLIENTE PRIMARY KEY (CLIENTE_SK)
);

CREATE TABLE DIM_TIEMPO (
    TIEMPO_SK        INT NOT NULL AUTO_INCREMENT,
    FECHA            DATE NOT NULL,
    DIA              INT,
    MES              INT,
    NOMBRE_MES       VARCHAR(20),
    TRIMESTRE        INT,
    ANIO             INT,
    SEMANA_ANIO      INT,
    DIA_SEMANA       INT,
    NOMBRE_DIA       VARCHAR(20),
    CONSTRAINT PK_DIM_TIEMPO PRIMARY KEY (TIEMPO_SK),
    CONSTRAINT UQ_DIM_TIEMPO_FECHA UNIQUE (FECHA)                      -- [A2]
);

CREATE TABLE DIM_PRODUCTO (
    PRODUCTO_SK      BIGINT NOT NULL AUTO_INCREMENT,
    PRODUCTO_ID      VARCHAR(50),
    NOMBRE_PRODUCTO  VARCHAR(150),
    CATEGORIA        VARCHAR(100),
    SUBCATEGORIA     VARCHAR(100),
    MARCA            VARCHAR(100),
    CONSTRAINT PK_DIM_PRODUCTO PRIMARY KEY (PRODUCTO_SK),
    CONSTRAINT UQ_DIM_PRODUCTO_ID UNIQUE (PRODUCTO_ID)                 -- [A2]
);

CREATE TABLE DIM_SUCURSAL (
    SUCURSAL_SK      BIGINT NOT NULL AUTO_INCREMENT,
    SUCURSAL_ID      VARCHAR(50),
    NOMBRE_SUCURSAL  VARCHAR(150),
    CIUDAD           VARCHAR(100),
    ESTADO           VARCHAR(100),
    REGION           VARCHAR(100),
    CONSTRAINT PK_DIM_SUCURSAL PRIMARY KEY (SUCURSAL_SK),
    CONSTRAINT UQ_DIM_SUCURSAL_ID UNIQUE (SUCURSAL_ID)                 -- [A2]
);

CREATE TABLE DIM_CANAL (
    CANAL_SK         INT NOT NULL AUTO_INCREMENT,
    CANAL_ID         VARCHAR(50),
    NOMBRE_CANAL     VARCHAR(100),
    TIPO_CANAL       VARCHAR(50),
    CONSTRAINT PK_DIM_CANAL PRIMARY KEY (CANAL_SK)
);

CREATE TABLE DIM_PROMOCION (
    PROMOCION_SK     BIGINT NOT NULL AUTO_INCREMENT,
    PROMOCION_ID     VARCHAR(50),
    NOMBRE_PROMOCION VARCHAR(150),
    TIPO_PROMOCION   VARCHAR(100),
    PORCENTAJE_DESC  DECIMAL(5,2),
    FECHA_INICIO     DATE,
    FECHA_FIN        DATE,
    CONSTRAINT PK_DIM_PROMOCION PRIMARY KEY (PROMOCION_SK)
);

/* Grano: una línea de venta (un producto dentro de un ticket/orden) */
CREATE TABLE FACT_VENTAS_LINEA (
    VENTA_LINEA_SK         BIGINT NOT NULL AUTO_INCREMENT,
    CLIENTE_SK             BIGINT NOT NULL,
    TIEMPO_SK              INT NOT NULL,
    PRODUCTO_SK            BIGINT NOT NULL,
    SUCURSAL_SK            BIGINT NOT NULL,
    CANAL_SK               INT NOT NULL,
    PROMOCION_SK           BIGINT,
    ORDEN_ID               VARCHAR(50) NOT NULL,
    LINEA_ORDEN            INT NOT NULL,
    UNIDADES               DECIMAL(18,3) NOT NULL,
    VENTA_BRUTA            DECIMAL(18,2) NOT NULL,
    MONTO_DESCUENTO        DECIMAL(18,2) NOT NULL,
    MONTO_IMPUESTO         DECIMAL(18,2) NOT NULL,
    MONTO_DEVOLUCION       DECIMAL(18,2) NOT NULL,
    COSTO_TOTAL            DECIMAL(18,2) NOT NULL,
    VENTA_NETA             DECIMAL(18,2) NOT NULL,
    MARGEN_BRUTO_MONETARIO DECIMAL(18,2) NOT NULL,
    MARGEN_PORCENTUAL      DECIMAL(9,4),
    TICKET_PROMEDIO        DECIMAL(18,2),
    UNIDADES_POR_ORDEN     DECIMAL(18,3),
    CONSTRAINT PK_FACT_VENTAS_LINEA PRIMARY KEY (VENTA_LINEA_SK),
    CONSTRAINT UQ_FACT_GRANO UNIQUE (ORDEN_ID, LINEA_ORDEN),           -- [A2]
    CONSTRAINT FK_FACT_CLIENTE   FOREIGN KEY (CLIENTE_SK)   REFERENCES DMI_CLIENTE(CLIENTE_SK),
    CONSTRAINT FK_FACT_TIEMPO    FOREIGN KEY (TIEMPO_SK)    REFERENCES DIM_TIEMPO(TIEMPO_SK),
    CONSTRAINT FK_FACT_PRODUCTO  FOREIGN KEY (PRODUCTO_SK)  REFERENCES DIM_PRODUCTO(PRODUCTO_SK),
    CONSTRAINT FK_FACT_SUCURSAL  FOREIGN KEY (SUCURSAL_SK)  REFERENCES DIM_SUCURSAL(SUCURSAL_SK),
    CONSTRAINT FK_FACT_CANAL     FOREIGN KEY (CANAL_SK)     REFERENCES DIM_CANAL(CANAL_SK),
    CONSTRAINT FK_FACT_PROMOCION FOREIGN KEY (PROMOCION_SK) REFERENCES DIM_PROMOCION(PROMOCION_SK)
);
